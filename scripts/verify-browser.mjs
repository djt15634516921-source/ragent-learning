// 可选的真实 Edge 回归，使用主验证脚本提供的隔离服务与本机假模型。
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {verifyLifecycleBrowser} from './verify-lifecycle-browser.mjs';
import {verifyRerankBrowser} from './verify-rerank-browser.mjs';

export async function verifyBrowser({root, origin, work, passed}) {
  const require = createRequire(import.meta.url);
  const {chromium} = require(join(root, 'target/browser-check/node_modules/playwright-core'));
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  try {
    const context = await browser.newContext({acceptDownloads: true});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin + '/login-test.html');
    await page.locator('#username').fill('page_user');
    await page.locator('#password').fill('local-test-123');
    await page.locator('#register').click();
    await page.waitForFunction(() => document.querySelector('#auth-status').textContent.includes('已创建'));
    await page.locator('#login').click();
    await page.waitForFunction(() => document.querySelector('#auth-status').textContent.includes('已登录'));
    assert.match(await page.locator('#knowledge-mode-status').textContent(), /普通聊天.*未使用知识库/);
    assert.ok(await page.evaluate(() => !!sessionStorage.getItem('ragent-learning-token')));
    assert.equal((await context.cookies()).length, 0);
    await page.locator('#mode').selectOption('normal');
    await page.locator('#question').fill('浏览器普通聊天');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('回答已完成并保存'));
    await page.waitForFunction(() => document.querySelector('#history').textContent.includes('浏览器普通聊天'));
    assert.match(await page.locator('#history').textContent(), /浏览器普通聊天/);
    assert.match(await page.locator('#chat-status').textContent(), /普通聊天.*未使用知识库/);
    await page.locator('#mode').selectOption('stream');
    await page.locator('#question').fill('浏览器流式聊天');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('回答已完成并保存'));
    await page.waitForFunction(() => document.querySelector('#history').textContent.includes('浏览器流式聊天'));
    await page.waitForFunction(() => !document.querySelector('#chat-fields').disabled);
    await page.goto(origin + '/stream-test.html');
    await page.locator('#conversation-id').fill('browser-stream');
    await page.locator('#question').fill('独立流式页面');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已完成并保存本轮'));
    passed('真实 Edge：注册、登录、sessionStorage、普通聊天和两个 SSE 页面');

    await page.goto(origin + '/knowledge-test.html');
    await page.waitForFunction(() => document.querySelector('#identity').dataset.authenticated === 'true');
    await page.locator('#name').fill('浏览器知识库');
    await page.locator('#description').fill('验证新的请求认证协议');
    await page.locator('#create-form button').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已创建知识库'));
    await page.locator('#file').setInputFiles({name: 'browser-note.md', mimeType: 'text/markdown',
      buffer: Buffer.from('# 浏览器验证\n朱之文01，原文解析与下载。\n\n' + 'Java 学习文档需要切分成片段，保留顺序和来源。'.repeat(350))});
    await page.locator('#upload-form button').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已上传'));
    await page.getByRole('button', {name: '解析文本', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('解析完成'));
    assert.match(await page.locator('#parsed-text').textContent(), /朱之文01/);
    await page.getByRole('button', {name: '切分文本', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('切分完成'));
    assert.ok(await page.locator('#chunks li').count() > 0);
    await page.locator('#chunk-next').click();
    await page.waitForFunction(() => document.querySelector('#chunk-summary').textContent.includes('第 2/'));
    await page.locator('#chunk-prev').click();
    await page.waitForFunction(() => document.querySelector('#chunk-summary').textContent.includes('第 1/'));
    await page.reload();
    await page.getByRole('button', {name: '查看片段', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#chunks').children.length > 0);
    await page.getByRole('button', {name: '重新解析', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('解析完成'));
    await page.getByRole('button', {name: '查看片段', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#chunk-summary').textContent.includes('尚未切分'));
    await page.getByRole('button', {name: '切分文本', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('切分完成'));
    passed('真实 Edge：文档切分、片段翻页、刷新恢复及重解析失效提示');
    await page.getByRole('button', {name: '向量化', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('向量化完成'));
    const downloaded = page.waitForEvent('download');
    await page.getByRole('link', {name: 'browser-note.md', exact: true}).click();
    const file = await downloaded;
    assert.equal(file.suggestedFilename(), 'browser-note.md');
    assert.match(readFileSync(await file.path(), 'utf8'), /朱之文01/);
    assert.ok(!file.url().includes('Bearer'));
    await page.reload();
    await page.getByRole('button', {name: '查看文本', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#parsed-text').textContent.includes('朱之文01'));
    await page.screenshot({path: join(work, 'knowledge-page.png'), fullPage: true});
    await page.locator('#agent-create').click();
    await page.waitForFunction(() => document.querySelector('#agent-status').textContent.includes('已创建 Agent 会话'));
    const agentConversationId = await page.locator('#agent-conversation').inputValue();
    assert.match(agentConversationId, /^[a-f0-9-]{36}$/);
    await page.locator('#agent-question').fill('请查浏览器资料的学习代号');
    await page.getByRole('button', {name: '向 Agent 提问'}).click();
    await page.waitForFunction(() => document.querySelector('#agent-status').textContent.includes('回答完成'));
    assert.match(await page.locator('#agent-answer').textContent(), /朱之文01.*\[1\]/s);
    assert.match(await page.locator('#agent-calls').textContent(), /search_knowledge.*找到资料.*\[1\]/);
    assert.match(await page.locator('#agent-sources summary').first().textContent(), /\[1\].*browser-note.md/);
    await page.locator('#agent-panel').screenshot({path: join(work, 'agent-knowledge-page.png')});
    passed('真实 Edge：Agent 问答显示模型检索词、返回资料、答案与引用编号');
    await page.waitForFunction(() => !document.querySelector('#workspace').disabled);
    await page.reload();
    await page.locator('#agent-conversation').selectOption(agentConversationId);
    await page.waitForFunction(() => document.querySelector('#agent-history').textContent.includes('请查浏览器资料的学习代号'));
    await page.getByRole('button', {name: '查看这轮工具和来源'}).click();
    assert.match(await page.locator('#agent-calls').textContent(), /search_knowledge/);
    assert.match(await page.locator('#agent-sources summary').first().textContent(), /browser-note.md/);
    await page.locator('#agent-panel').screenshot({path: join(work, 'agent-conversation-page.png')});
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#agent-delete').click();
    await page.waitForFunction(() => document.querySelector('#agent-status').textContent.includes('已删除 Agent 会话'));
    assert.equal(await page.locator('#agent-conversation').inputValue(), '');
    assert.equal(await page.locator('#agent-history li').count(), 0);
    passed('真实 Edge：创建并重开 Agent 会话，回看历史工具和来源，删除后清空会话界面');
    await page.goto(origin + '/login-test.html');
    await page.waitForFunction(() => document.querySelector('#auth-status').textContent.includes('已登录'));
    await page.locator('#chat-knowledge-base').selectOption({label: '浏览器知识库'});
    assert.match(await page.locator('#knowledge-mode-status').textContent(), /知识库问答.*浏览器知识库/);
    await page.locator('#question').fill('浏览器资料的学习代号是什么？');
    await page.locator('#mode').selectOption('normal');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('回答已完成并保存'));
    assert.ok(await page.locator('#sources details').count() > 0);
    assert.match(await page.locator('#chat-status').textContent(), /知识库问答.*资料片段/);
    assert.match(await page.locator('#answer').textContent(), /朱之文01/);
    assert.match(await page.locator('#retrieval-query').textContent(), /首轮使用原问题/);
    await page.waitForFunction(() => !document.querySelector('#chat-fields').disabled);
    await page.locator('#mode').selectOption('stream');
    await page.locator('#question').fill('再说一下浏览器资料的学习代号');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('回答已完成并保存'));
    assert.ok(await page.locator('#sources details').count() > 0);
    await page.waitForFunction(() => document.querySelector('#history').textContent.includes('来源：'));
    await page.waitForFunction(() => !document.querySelector('#chat-fields').disabled);
    await page.locator('#question').fill('它的学习代号是什么？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('回答已完成并保存'));
    assert.match(await page.locator('#retrieval-query').textContent(), /已补全追问对象.*浏览器资料的学习代号是什么/);
    assert.equal(await page.locator('#question').inputValue(), '它的学习代号是什么？');
    await page.waitForFunction(() => document.querySelector('#history').textContent.includes('它的学习代号是什么？'));
    await page.waitForFunction(() => !document.querySelector('#chat-fields').disabled);
    await page.screenshot({path: join(work, 'rag-chat-page.png'), fullPage: true});
    passed('真实 Edge：手动向量化、选择知识库、普通/SSE 问答和资料来源显示');
    passed('真实 Edge：连续追问显示补全后的检索问题，输入框与历史保留用户原话');
    await verifyLifecycleBrowser({page,origin,work,passed});
    await verifyRerankBrowser({page,origin,work,passed});
    await page.locator('#logout').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('已退出'));
    assert.ok(await page.evaluate(() => !sessionStorage.getItem('ragent-learning-token')));
    assert.equal(await page.locator('#sources details').count(), 0);
    assert.equal(await page.locator('#retrieval-query').isHidden(), true);
    await page.goto(origin + '/knowledge-test.html');
    await page.waitForFunction(() => document.querySelector('#identity').dataset.authenticated === 'false');
    assert.deepEqual(errors, []);
    passed('真实 Edge：上传、解析、读取文本、携带请求头下载、刷新和退出清理');
  } finally { await browser.close(); }
}
